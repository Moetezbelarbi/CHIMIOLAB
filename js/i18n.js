let currentLang = LANG_DEFAULT;
const listeners = new Set();

export function getLang() { return currentLang; }
export function setLang(lang) {
  if (!LANGS.includes(lang)) lang = LANG_DEFAULT;
  currentLang = lang;
  try { localStorage.setItem(STORAGE_KEY_LANG, lang); } catch (_) {}
  listeners.forEach(fn => { try { fn(lang); } catch (_) {} });
}
export function initLang() {
  let lang = LANG_DEFAULT;
  try {
    const saved = localStorage.getItem(STORAGE_KEY_LANG);
    if (saved && LANGS.includes(saved)) lang = saved;
    else if (navigator.language && navigator.language.toLowerCase().startsWith("en")) lang = "en";
  } catch (_) {}
  currentLang = lang;
}
export function t(key) {
  const d = DICT[currentLang] || DICT[LANG_DEFAULT];
  if (key in d) return d[key];
  const fallback = DICT[LANG_DEFAULT];
  if (key in fallback) return fallback[key];
  return key;
}
export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
export function applyI18nToDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"))); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
}